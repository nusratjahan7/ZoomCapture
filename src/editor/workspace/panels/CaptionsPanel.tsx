/**
 * Captions (Module 08): subtitles added by hand or generated by speech recognition running on this
 * device, then reviewed and corrected here. Each cue has a start, an end and text with line
 * breaks; one style applies to all. They are shown in the preview, burned into the exported video
 * (unless turned off) and can be downloaded as .srt or .vtt.
 */
export function CaptionsPanel() {
  const { store, recording, player, reportError } = useEditor();
  const project = useEditorState((snapshot) => snapshot.project);
  const style = subtitleStyleOf(project);
  const cues = mainTrack(project.subtitles)?.cues ?? [];
  const edit = (label: string, change: (p: Project) => Project, mergeKey?: string) => store.edit(label, change, { mergeKey });
  const setStyle = (patch: Partial<SubtitleStyle>, mergeKey?: string) => edit('Change subtitle style', (p) => ({ ...p, subtitleStyle: { ...subtitleStyleOf(p), ...patch } }), mergeKey);
  const listRef = useRef<HTMLUListElement>(null);

  // The cue under the playhead is highlighted (updated without re-rendering every frame).
  usePlayheadListener((timeMs) => {
    for (const item of listRef.current?.querySelectorAll<HTMLElement>('[data-cue]') ?? []) {
      item.dataset.current = String(timeMs >= Number(item.dataset.start) && timeMs < Number(item.dataset.end));
    }
  }, player);

  const add = () => {
    let cueId = '';
    edit('Add subtitle', (p) => {
      const result = addCue(p.subtitles, player?.time ?? 0);
      cueId = result.cueId;
      return { ...p, subtitles: result.subtitles };
    });
    requestAnimationFrame(() => listRef.current?.querySelector<HTMLTextAreaElement>(`[data-cue="${cueId}"] textarea`)?.focus());
  };

  const download = (format: 'srt' | 'vtt') => {
    const text = format === 'srt' ? toSrt(cues) : toVtt(cues);
    downloadBlob(new Blob([text], { type: format === 'srt' ? 'application/x-subrip' : 'text/vtt' }), `${recording.name}.${format}`);
  };

  return (
    <div data-testid="captions-panel">
      <PanelSection title="Subtitles" actions={<Button size="sm" icon={Plus} onClick={add}>Add at playhead</Button>}>
        {cues.length === 0 ? (
          <p className="rounded-lg border border-dashed border-line p-3 text-center text-xs text-fg-subtle">No subtitles yet. Add them by hand, or generate them from the speech below.</p>
        ) : (
          <ul ref={listRef} className="space-y-2" aria-label="Subtitles">
            {cues.map((cue) => (
              <CueRow
                key={cue.id}
                cue={cue}
                onSeek={() => player?.seek(cue.startMs)}
                onChange={(label, patch, mergeKey) => {
                  try {
                    edit(label, (p) => ({ ...p, subtitles: updateCue(p.subtitles, cue.id, patch) }), mergeKey);
                  } catch (error) {
                    reportError(getErrorMessage(error));
                  }
                }}
                onDelete={() => edit('Delete subtitle', (p) => ({ ...p, subtitles: deleteCue(p.subtitles, cue.id) }))}
                playheadMs={() => player?.time ?? 0}
              />
            ))}
          </ul>
        )}
        {cues.length > 0 && (
          <div className="flex flex-wrap gap-1.5">
            <Button size="sm" variant="ghost" icon={Download} onClick={() => download('srt')}>
              .srt
            </Button>
            <Button size="sm" variant="ghost" icon={Download} onClick={() => download('vtt')}>
              .vtt
            </Button>
          </div>
        )}
      </PanelSection>

      <AutoSubtitles hasCues={cues.length > 0} />

      <PanelSection title="Style">
        <Toggle label="Show subtitles" description="In the preview and burned into exported videos" checked={style.visible} onCheckedChange={(visible) => setStyle({ visible })} />
        <ChoiceGrid label="Font" options={FONT_OPTIONS} value={style.font} onChange={(font) => setStyle({ font })} />
        <SliderField label="Size" value={style.size} min={LIMITS.subtitleSize.min} max={LIMITS.subtitleSize.max} step={0.005} display={percent} onChange={(size) => setStyle({ size }, 'sub-size')} />
        <ColorField label="Text colour" value={style.color} onChange={(color) => setStyle({ color }, 'sub-color')} />
        <Toggle label="Background box" checked={style.background !== null} onCheckedChange={(on) => setStyle({ background: on ? '#000000' : null })} />
        {style.background !== null && (
          <>
            <ColorField label="Box colour" value={style.background} onChange={(background) => setStyle({ background }, 'sub-bg')} />
            <SliderField label="Box opacity" value={style.backgroundOpacity} min={0} max={1} step={0.05} display={percent} onChange={(backgroundOpacity) => setStyle({ backgroundOpacity }, 'sub-bg-opacity')} />
          </>
        )}
        <FieldRow label="Position">
          <SegmentedControl
            label="Subtitle position"
            options={[
              { value: 'top', label: 'Top' },
              { value: 'middle', label: 'Middle' },
              { value: 'bottom', label: 'Bottom' },
            ]}
            value={style.position}
            onChange={(position) => setStyle({ position })}
          />
        </FieldRow>
        {style.position !== 'middle' && <SliderField label="Margin" value={style.margin} min={0} max={0.3} step={0.01} display={percent} onChange={(margin) => setStyle({ margin }, 'sub-margin')} />}
      </PanelSection>
    </div>
  );
}

function CueRow({
  cue,
  onSeek,
  onChange,
  onDelete,
  playheadMs,
}: {
  cue: SubtitleCue;
  onSeek: () => void;
  onChange: (label: string, patch: Partial<Pick<SubtitleCue, 'startMs' | 'endMs' | 'text'>>, mergeKey?: string) => void;
  onDelete: () => void;
  playheadMs: () => number;
}) {
  const textId = useId();
  // Typing keeps its own draft (line breaks included) and is saved as one undo step per pause.
  const [draft, setDraft] = useState(cue.text);
  useEffect(() => setDraft(cue.text), [cue.text]);
  return (
    <li
      data-cue={cue.id}
      data-start={cue.startMs}
      data-end={cue.endMs}
      className="space-y-1.5 rounded-xl border border-transparent bg-surface-2 p-2 data-[current=true]:border-accent/60"
    >
      <div className="grid grid-cols-[1fr_1fr_auto] items-end gap-1.5">
        <CompactTime label="Start" value={cue.startMs} onCommit={(startMs) => onChange('Change subtitle start', { startMs })} onNow={() => onChange('Change subtitle start', { startMs: playheadMs() })} />
        <CompactTime label="End" value={cue.endMs} onCommit={(endMs) => onChange('Change subtitle end', { endMs })} onNow={() => onChange('Change subtitle end', { endMs: playheadMs() })} />
        <IconButton icon={Trash2} label="Delete subtitle" size="sm" tone="danger" tooltipAlign="end" className="size-7" onClick={onDelete} />
      </div>
      <label htmlFor={textId} className="sr-only">
        Subtitle text
      </label>
      <textarea
        id={textId}
        value={draft}
        rows={2}
        maxLength={500}
        onFocus={onSeek}
        onChange={(event) => {
          setDraft(event.target.value);
          onChange('Edit subtitle', { text: event.target.value }, `cue-text:${cue.id}`);
        }}
        className="w-full resize-y rounded-lg border border-line-strong bg-surface-3 p-1.5 text-xs text-fg"
        placeholder="Subtitle text (Enter for a new line)"
      />
    </li>
  );
}

function CompactTime({ label, value, onCommit, onNow }: { label: string; value: number; onCommit: (ms: number) => void; onNow: () => void }) {
  return (
    <div className="min-w-0 [&_label]:text-[10px]">
      <TimeField label={label} value={value} onCommit={onCommit} stacked />
      <button type="button" onClick={onNow} className="mt-0.5 text-[10px] text-fg-subtle underline hover:text-fg">
        Set to playhead
      </button>
    </div>
  );
}

/** Speech recognition on this device (see services/transcription). */
function AutoSubtitles({ hasCues }: { hasCues: boolean }) {
  const { store, assets } = useEditor();
  const toast = useToast();
  const project = useEditorState((snapshot) => snapshot.project);
  const assetMap = useMemo(() => new Map(assets.map((asset) => [asset.id, asset])), [assets]);
  const tracks = transcribableTracks(project.timeline, assetMap);
  // The microphone (or a voiceover) is usually the clearest speech; else the recording's sound.
  const preferred = tracks.find((track) => track.kind === 'audio') ?? tracks[0];
  const [chosen, setChosen] = useState<string[] | null>(null);
  const trackIds = chosen ?? (preferred ? [preferred.id] : []);
  const [model, setModel] = useState<TranscriptionModel>(TRANSCRIPTION_MODELS[0].id);
  const [progress, setProgress] = useState<TranscriptionProgress | null>(null);
  const [confirm, setConfirm] = useState(false);
  const abort = useRef<AbortController | null>(null);
  useEffect(() => () => abort.current?.abort(), []);

  const run = async () => {
    const controller = new AbortController();
    abort.current = controller;
    setProgress({ stage: 'preparing' });
    try {
      await store.flush();
      const audio = await timelineSpeech(store.project.timeline, trackIds, assetMap, (id) => getAssetBlob(id));
      const cues = await transcribe(audio, { model, signal: controller.signal, onProgress: setProgress });
      if (controller.signal.aborted) return;
      if (cues.length === 0) {
        toast.show({ title: 'No speech found', description: 'Nothing was recognised in the chosen tracks. Try another track, or add subtitles by hand.' });
        return;
      }
      store.edit('Generate subtitles', (p) => ({ ...p, subtitles: replaceCues(p.subtitles, cues), subtitleStyle: subtitleStyleOf(p) }));
      toast.show({ variant: 'success', title: `${cues.length} subtitles generated`, description: 'Review them: play them back and correct the words and times above.' });
    } catch (error) {
      if (error instanceof DOMException && error.name === 'AbortError') return;
      logDiagnostic('transcription', error);
      toast.show({ variant: 'error', title: 'Subtitles were not generated', description: error instanceof TranscriptionError ? error.message : getErrorMessage(error) });
    } finally {
      if (abort.current === controller) abort.current = null;
      setProgress(null);
    }
  };

  return (
    <PanelSection title="Generate from speech">
      <p className="text-xs text-fg-muted">
        Speech recognition (OpenAI Whisper) runs on this device: the audio is not uploaded. The first time, the speech model is downloaded from Hugging Face and then kept in this
        browser. Always review the result: names and quiet speech can come out wrong.
      </p>
      {tracks.length === 0 ? (
        <p className="text-xs text-fg-subtle">Nothing on the timeline has sound to transcribe.</p>
      ) : (
        <>
          <fieldset className="space-y-1">
            <legend className="text-xs text-fg-muted">Speech from</legend>
            {tracks.map((track) => (
              <label key={track.id} className="flex items-center gap-2 text-xs">
                <input
                  type="checkbox"
                  checked={trackIds.includes(track.id)}
                  disabled={progress !== null}
                  onChange={(event) => setChosen(event.target.checked ? [...trackIds, track.id] : trackIds.filter((id) => id !== track.id))}
                  className="size-4 accent-[var(--color-accent)]"
                />
                {track.name}
              </label>
            ))}
          </fieldset>
          <label className="flex items-center gap-2 text-xs text-fg-muted">
            Model
            <select value={model} disabled={progress !== null} onChange={(event) => setModel(event.target.value as TranscriptionModel)} className="h-8 min-w-0 flex-1 rounded-lg border border-line bg-surface-2 px-1.5 text-xs text-fg">
              {TRANSCRIPTION_MODELS.map((option) => (
                <option key={option.id} value={option.id}>
                  {option.label}
                </option>
              ))}
            </select>
          </label>
          {progress ? (
            <div className="space-y-1.5" role="status" aria-live="polite" data-testid="transcription-progress">
              <p className="flex items-center gap-2 text-xs text-fg-muted">
                <Loader2 size={13} aria-hidden className="animate-spin" />
                {progress.stage === 'preparing'
                  ? 'Preparing the audio…'
                  : progress.stage === 'downloading'
                    ? `Downloading the speech model… ${progress.total ? `${formatBytes(progress.loaded)} of ${formatBytes(progress.total)}` : ''}`
                    : progress.total
                      ? `Transcribing… ${progress.done} of ${progress.total} parts`
                      : 'Transcribing…'}
              </p>
              <div className="h-1.5 overflow-hidden rounded-full bg-surface-3">
                <div
                  className={cn('h-full bg-accent transition-[width]', progress.stage === 'preparing' && 'w-1/12 animate-pulse')}
                  style={progress.stage === 'downloading' && progress.total ? { width: `${(progress.loaded / progress.total) * 100}%` } : progress.stage === 'transcribing' ? { width: `${progress.total ? (progress.done / progress.total) * 100 : 5}%` } : undefined}
                />
              </div>
              <Button size="sm" variant="ghost" icon={X} onClick={() => abort.current?.abort()}>
                Cancel
              </Button>
            </div>
          ) : (
            <Button size="sm" icon={hasCues ? Captions : Sparkles} disabled={trackIds.length === 0} onClick={() => (hasCues ? setConfirm(true) : void run())}>
              Generate subtitles
            </Button>
          )}
        </>
      )}
      <ConfirmDialog
        open={confirm}
        onClose={() => setConfirm(false)}
        onConfirm={() => void run()}
        title="Replace the subtitles?"
        description="The generated subtitles replace the current ones (undo brings them back)."
        confirmLabel="Generate"
      />
    </PanelSection>
  );
}
